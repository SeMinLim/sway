#!/usr/bin/env python3
"""Export the frozen integer contract as standalone C constants and fixtures."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

import numpy as np


ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "hw" / "reference"))
from integer_model import IntegerModel, requantize


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def initializer(array, indent=1):
    array = np.asarray(array)
    if array.ndim == 1:
        lines = []
        for offset in range(0, array.size, 20):
            lines.append("\t" * (indent + 1) + ", ".join(str(int(v)) for v in array[offset:offset + 20]))
        return "{\n" + ",\n".join(lines) + "\n" + "\t" * indent + "}"
    lines = ["\t" * (indent + 1) + initializer(row, indent + 1) for row in array]
    return "{\n" + ",\n".join(lines) + "\n" + "\t" * indent + "}"


def generate():
    model = IntegerModel()
    generated = ROOT / "hw" / "generated"
    frozen = np.load(generated / "test_trace.npz", allow_pickle=False)
    inputs = frozen["input"].astype(np.int8)
    outputs = model.forward_integer(inputs).astype(np.int8)
    if not np.array_equal(outputs, frozen["output"]):
        raise ValueError("Frozen test outputs differ from the integer reference")
    real = model.quantize_inputs(np.load(ROOT / "hw" / "model" / "real_fixture_features.npy", allow_pickle=False))
    if not np.array_equal(inputs[:len(real)], real):
        raise ValueError("Frozen input fixtures do not start with the real MARS frames")

    # Compose quantization and nonlinear lookup exactly, without fitting a function.
    exp_products = []
    gate_inputs = []
    operand_values = np.arange(-128, 128, dtype=np.int64)
    all_products = operand_values[:, None] * operand_values[None, :]
    for block, size in enumerate((2048, 512)):
        prefix = "blocks.%d." % block
        product_exponent = model.exponent(prefix + "delta") + model.exponent(prefix + "A")
        exp_exponent = model.exponent(prefix + "expInput")
        product_values = np.arange(-size // 2, size // 2, dtype=np.int64)
        product_table = model.tables[2 * block + 1, requantize(product_values, product_exponent, exp_exponent) + 128]
        expected = model.tables[2 * block + 1, requantize(all_products, product_exponent, exp_exponent) + 128]
        actual = product_table[np.clip(all_products, -size // 2, size // 2 - 1) + size // 2]
        if not np.array_equal(actual, expected):
            raise ValueError("Composed exponential table is not exact for block %d" % block)
        exp_products.append(product_table)
        gate = model.tables[2 * block, requantize(operand_values, model.exponent(prefix + "in"),
                                                model.exponent(prefix + "gateInput")) + 128]
        for index, value in enumerate(operand_values):
            separate = model.tables[2 * block, int(requantize(value, model.exponent(prefix + "in"),
                                                            model.exponent(prefix + "gateInput"))) + 128]
            if gate[index] != separate:
                raise ValueError("Composed gate table is not exact")
        gate_inputs.append(gate)
    norm_reciprocal = np.asarray([(1 << 32) // (20 * max(span, 1)) for span in range(256)], dtype=np.uint32)

    header = ["/* Generated by tools/export_model.py. Do not edit. */",
              "#ifndef SWAY_MODEL_H", "#define SWAY_MODEL_H", "", '#include "../sway.h"', ""]
    for name, node in model.profile["nodes"].items():
        macro = re.sub(r"[^A-Za-z0-9]", "_", name).upper()
        header.append("#define SWAY_EXP_%s (%d)" % (macro, node["exponent"]))
    header += ["", "extern const SwayModel swayModel;", "", "#endif", ""]

    source = ['/* Generated from hash-verified frozen INT8 tensors. */', '#include "sway_model.h"', "",
              "const SwayModel swayModel __attribute__((aligned(4))) = {"]
    def member(name, value, depth=1):
        source.append("\t" * depth + "." + name + " = " + initializer(value, depth) + ",")
    member("embeddingWeight", model.parameters["embedding.weight"])
    member("embeddingBias", model.parameters["embedding.bias"])
    source.append("\t.blocks = {")
    fields = [("normWeight", "normWeight"), ("normBias", "normBias"),
              ("inWeight", "inWeight"), ("convWeight", "convWeight"),
              ("convBias", "convBias"), ("xWeight", "xWeight"),
              ("dtWeight", "dtWeight"), ("dtBias", "dtBias"),
              ("aWeight", "A"), ("dWeight", "D"), ("outWeight", "outWeight")]
    for block in range(2):
        source.append("\t\t{")
        for field, parameter in fields:
            value = model.parameters["blocks.%d.%s" % (block, parameter)]
            if field == "convWeight":
                value = value.reshape(40, 4)
            member(field, value, 3)
        source.append("\t\t},")
    source.append("\t},")
    member("headWeight", model.parameters["headHidden.weight"])
    member("headBias", model.parameters["headHidden.bias"])
    member("outputWeight", model.parameters["headOutput.weight"])
    member("outputBias", np.pad(model.parameters["headOutput.bias"], (0, 3)))
    member("tables", model.tables)
    member("expProduct0", exp_products[0])
    member("expProduct1", exp_products[1])
    member("gateInputTable", np.stack(gate_inputs))
    member("normReciprocal", norm_reciprocal)
    source += ["};", ""]

    fixture_header = ["/* Generated by tools/export_model.py. Do not edit. */",
                      "#ifndef SWAY_FIXTURES_H", "#define SWAY_FIXTURES_H", "",
                      "#include <stdint.h>", "",
                      "#define SWAY_FIXTURE_FRAMES %d" % len(inputs),
                      "#define SWAY_REAL_FRAMES %d" % len(real), "",
                      "extern const int8_t swayFixtureInput[SWAY_FIXTURE_FRAMES][320];",
                      "extern const int8_t swayFixtureExpected[SWAY_FIXTURE_FRAMES][57];", "",
                      "#endif", ""]
    fixture_source = ["/* First eight inputs are real MARS test frames; remaining six are stress/reset fixtures. */",
                      '#include "sway_fixtures.h"', "",
                      "const int8_t swayFixtureInput[SWAY_FIXTURE_FRAMES][320] __attribute__((aligned(4))) = " +
                      initializer(inputs.reshape(-1, 320), 0) + ";", "",
                      "const int8_t swayFixtureExpected[SWAY_FIXTURE_FRAMES][57] __attribute__((aligned(4))) = " +
                      initializer(outputs, 0) + ";", ""]
    files = {"sway_model.h": "\n".join(header), "sway_model.c": "\n".join(source),
             "sway_fixtures.h": "\n".join(fixture_header), "sway_fixtures.c": "\n".join(fixture_source)}
    paths = [ROOT / "hw/reference/integer_model.py", ROOT / "hw/model/export/manifest.json",
             ROOT / "hw/model/export/quantization.json", generated / "nonlinear_tables.npy",
             generated / "test_trace.npz", ROOT / "hw/model/real_fixture_features.npy"]
    paths.extend(model.export / entry["binary"] for entry in model.manifest["tensors"])
    provenance = {
        "schemaVersion": 1,
        "contract": "hw/reference/integer_model.py; exact integer normalization, ties-to-even, INT24 current / INT17 retained state",
        "parameterValues": sum(value.size for value in model.parameters.values()),
        "nonlinearTableValues": int(model.tables.size),
        "derivedTables": {
            "expProductValues": [2048, 512], "gateInputValues": [256, 256], "normReciprocalValues": 256,
            "expProductVerification": "All 65536 signed-INT8 operand pairs per block match separate requantization and lookup",
            "gateInputVerification": "All 256 signed-INT8 inputs per block match separate requantization and lookup",
            "normalizationReciprocal": "floor(2^32 / (20 * max(span, 1))); integer quotient correction preserves exact rounding",
            "additionalBytes": 4096,
        },
        "inputShape": [8, 8, 5], "outputShape": [57],
        "inputExponent": model.exponent("input"), "outputExponent": model.exponent("output"),
        "fixtureFrames": len(inputs), "realFixtureFrames": len(real),
        "realTestIndices": [0, 1, 49, 249, 1023, 2047, 4095, 7983],
        "sourceSHA256": {str(path.relative_to(ROOT)): sha256(path) for path in paths},
        "generatedSHA256": {name: hashlib.sha256(content.encode()).hexdigest() for name, content in files.items()},
        "weightsChanged": False, "scalesChanged": False, "trainingPerformed": False,
    }
    files["provenance.json"] = json.dumps(provenance, indent=2) + "\n"
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "sw/c/generated")
    parser.add_argument("--check", action="store_true", help="Check committed exports without writing")
    args = parser.parse_args()
    files = generate()
    if args.check:
        different = [name for name, value in files.items()
                     if not (args.output_dir / name).is_file() or (args.output_dir / name).read_text() != value]
        if different:
            raise SystemExit("Export mismatch: " + ", ".join(different))
        print("Frozen C export matches all source tensors, scales, tables, and fixtures.")
        return
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, value in files.items():
        (args.output_dir / name).write_text(value)
    print("Exported %d files to %s" % (len(files), args.output_dir))


if __name__ == "__main__":
    main()
